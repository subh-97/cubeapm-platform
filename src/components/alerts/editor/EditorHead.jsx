import { useEffect, useRef, useState } from 'react'
import { BellRing, Pause, Play } from 'lucide-react'
import { ruleSentenceParts } from '@/utils/alerts/describe'
import { radioGroupKeyDown } from '@/components/alerts/shared/alertShared'
import { SUBDOMAINS, domainOf } from '@/utils/alerts/ruleTemplates'

// Which field a sentence token jumps to (D6: "each bold token jumps to its field").
const FIELD_FOR_PART = {
  metric: 'query', scope: 'query', condition: 'tiers', for: 'forSec', interval: 'intervalSec', notify: 'notify', repeat: 'repeatSec',
}

/**
 * The editor's head (D6). On the page, a row: the rule's name, a blank to fill
 * in (the template's or the card's name when the rule came with one; empty,
 * reading "Rule name", when it is new), the same name step 2 edits; and at
 * its right the status the rule will be saved with — Active or Paused, a pair of glyphs named by their labels and
 * titles; production copies a paused status into a clone and never shows it
 * (R41) — then a hairline, then the page's way out: Cancel outlined and Save
 * solid. Under the row, a tinted box: the rule as one sentence, generated by
 * describe.js from the draft as it stands, so a reviewer can read the whole
 * rule without opening a step, and every bold part jumps to its field; at its
 * right, for a rule started from a template, where that template lives
 * ("From template · APM · Services", its title for a screen reader).
 * `hideSummary` takes the sentence box away — while a template rule has moved
 * off its template, TemplateBanner below speaks for it — though the paused
 * note and the list of what is missing still show there when they are up.
 *
 * Save is never a dead grey button (R22): pressing it with something missing
 * lists what is, each a link to its field. The page asks for the list
 * (`listAsk` counts its asks), from this Save and the one at the end of the
 * last step; a step left with something missing says so on its own header.
 */
export default function EditorHead({ view, name, onName, nameProblem, template, hideSummary = false, status, onStatus, issues, onFocusField, onCancel, onSave, listAsk = 0, saving, mode }) {
  const [listOpen, setListOpen] = useState(false)
  const listRef = useRef(null)
  const wantFocus = useRef(false)
  const blocked = issues.length > 0
  const parts = ruleSentenceParts(view)

  // Each ask from Save opens the list, and once it is drawn its first item
  // takes focus.
  useEffect(() => {
    if (!listAsk) return
    wantFocus.current = true
    setListOpen(true)
  }, [listAsk])
  useEffect(() => {
    if (!wantFocus.current || !listOpen) return
    wantFocus.current = false
    listRef.current?.querySelector('button')?.focus()
  })

  return (
    <>
      {/* Held at the top while the page scrolls: a child of the page, not of
          the section below, since a sticky element holds only within its parent. */}
      <div className="ae-head-top">
        {/* A label, so the bell inside the blank puts the caret in it too. */}
        <label className={`ae-head-name-field${nameProblem ? ' invalid' : ''}`}>
          <BellRing className="ae-head-name-icon" aria-hidden="true" />
          <input
            className="ae-head-name"
            value={name}
            onChange={e => onName(e.target.value)}
            placeholder="Rule name"
            aria-label="Rule name"
            aria-invalid={nameProblem ? true : undefined}
            title={nameProblem || undefined}
            spellCheck={false}
            autoComplete="off"
          />
        </label>
        <div className="ae-head-actions">
          <div className="seg-toggle ae-status" role="radiogroup" aria-label="Save the rule as" onKeyDown={radioGroupKeyDown}>
            <button type="button" role="radio" aria-checked={status === 'ACTIVE'} aria-label="Active" title="Save active: evaluated and notifying" className={`seg${status === 'ACTIVE' ? ' active' : ''}`} tabIndex={status === 'ACTIVE' ? 0 : -1} onClick={() => onStatus('ACTIVE')}>
              <Play aria-hidden="true" />
            </button>
            <button type="button" role="radio" aria-checked={status === 'PAUSED'} aria-label="Paused" title="Save paused: not evaluated until resumed" className={`seg${status === 'PAUSED' ? ' active' : ''}`} tabIndex={status === 'PAUSED' ? 0 : -1} onClick={() => onStatus('PAUSED')}>
              <Pause aria-hidden="true" />
            </button>
          </div>
          <span className="ae-head-sep" aria-hidden="true" />
          <button type="button" className="hbtn ae-cancel" onClick={onCancel}>Cancel</button>
          <button
            type="button"
            className="hbtn primary ae-save"
            aria-disabled={saving || undefined}
            aria-describedby={blocked && listOpen ? 'ae-issues' : undefined}
            onClick={saving ? undefined : onSave}
          >
            {mode === 'edit' ? 'Save changes' : 'Save rule'}
          </button>
        </div>
      </div>
      {(!hideSummary || status === 'PAUSED' || (blocked && listOpen)) && (
        <section className="ae-head" aria-label="Rule summary">
          <div className="ae-head-box">
            {!hideSummary && (
              <div className="ae-head-line">
                <p className="ae-sentence" aria-live="polite">
                  {parts.map((p, i) => {
                    if (!FIELD_FOR_PART[p.field]) return <span key={i}>{p.text}</span>
                    // A token's own spaces stay outside its button, which would drop them.
                    const [, lead, core, trail] = /^(\s*)([\s\S]*?)(\s*)$/.exec(p.text)
                    return (
                      <span key={i}>
                        {lead}
                        <button type="button" className="ae-token" onClick={() => onFocusField(FIELD_FOR_PART[p.field])} title="Go to this field">{core}</button>
                        {trail}
                      </span>
                    )
                  })}
                </p>
                {template && (
                  <p className="ae-head-from" id="ae-tpl-head" tabIndex={-1}>
                    From template · {domainOf(template.home)?.label} · {SUBDOMAINS[template.home]?.label}<span className="sr-only">: {template.title}</span>
                  </p>
                )}
              </div>
            )}
            {status === 'PAUSED' && (
              <p className="ae-paused-note">
                This rule will be saved paused: it won&apos;t be evaluated or notify anyone until it&apos;s resumed.
              </p>
            )}
            {blocked && listOpen && (
              <div className="ae-issues" id="ae-issues" ref={listRef} role="region" aria-label="What to finish before saving">
                <p className="ae-issues-title">Finish these to save the rule:</p>
                <ul>
                  {issues.map((it, i) => (
                    <li key={`${it.field}-${i}`}>
                      <button type="button" className="ae-issue" onClick={() => onFocusField(it.field)}>{it.message}</button>
                    </li>
                  ))}
                </ul>
              </div>
            )}
          </div>
        </section>
      )}
    </>
  )
}
